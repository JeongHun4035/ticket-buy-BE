CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 name VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL CHECK (role IN ('USER','ADMIN'))
);
CREATE TABLE auth_session (
 id VARCHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 access_hash VARCHAR(64) NOT NULL UNIQUE, refresh_hash VARCHAR(64) NOT NULL UNIQUE,
 access_expires TIMESTAMP WITH TIME ZONE NOT NULL, refresh_expires TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE venue (id BIGINT PRIMARY KEY, names TEXT NOT NULL);
CREATE TABLE venue_seat (
 id BIGINT PRIMARY KEY, venue_id BIGINT NOT NULL REFERENCES venue(id),
 row_label VARCHAR(10) NOT NULL, seat_number INT NOT NULL, x INT NOT NULL, y INT NOT NULL,
 UNIQUE(venue_id,row_label,seat_number)
);
CREATE TABLE event (
 id BIGINT PRIMARY KEY, titles TEXT NOT NULL, descriptions TEXT NOT NULL,
 category VARCHAR(20) NOT NULL CHECK(category IN ('CONCERT','MUSICAL','THEATER','EXHIBITION','CLASSICAL')),
 poster_url TEXT, featured_rank INT NOT NULL DEFAULT 0
);
CREATE TABLE performance (
 id BIGINT PRIMARY KEY, event_id BIGINT NOT NULL REFERENCES event(id), venue_id BIGINT NOT NULL REFERENCES venue(id),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL, opens_at TIMESTAMP WITH TIME ZONE NOT NULL,
 closes_at TIMESTAMP WITH TIME ZONE NOT NULL, next_ticket BIGINT NOT NULL DEFAULT 0,
 CHECK(opens_at < closes_at), CHECK(closes_at <= starts_at)
);
CREATE TABLE queue_entry (
 id VARCHAR(36) PRIMARY KEY, performance_id BIGINT NOT NULL REFERENCES performance(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 ticket BIGINT NOT NULL, state VARCHAR(20) NOT NULL CHECK(state IN ('WAITING','ADMITTED','EXPIRED','CANCELLED')),
 token VARCHAR(64), expires_at TIMESTAMP WITH TIME ZONE, UNIQUE(performance_id,user_id), UNIQUE(performance_id,ticket)
);
CREATE INDEX queue_order ON queue_entry(performance_id,state,ticket);
CREATE TABLE seat_hold (
 id VARCHAR(36) PRIMARY KEY, performance_id BIGINT NOT NULL REFERENCES performance(id), user_id BIGINT NOT NULL REFERENCES app_user(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, state VARCHAR(20) NOT NULL CHECK(state IN ('ACTIVE','EXPIRED','RELEASED','CONSUMED'))
);
CREATE TABLE reservation (
 id VARCHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id), performance_id BIGINT NOT NULL REFERENCES performance(id),
 hold_id VARCHAR(36) NOT NULL UNIQUE REFERENCES seat_hold(id), idempotency_key VARCHAR(100) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CANCELLED')), payment_status VARCHAR(20) NOT NULL DEFAULT 'NOT_REQUIRED',
 total BIGINT NOT NULL CHECK(total>=0), created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,idempotency_key)
);
CREATE TABLE performance_seat (
 performance_id BIGINT NOT NULL REFERENCES performance(id), seat_id BIGINT NOT NULL REFERENCES venue_seat(id),
 grade VARCHAR(3) NOT NULL CHECK(grade IN ('VIP','R','S')), price BIGINT NOT NULL CHECK(price>=0),
 hold_id VARCHAR(36) REFERENCES seat_hold(id), reservation_id VARCHAR(36) REFERENCES reservation(id),
 PRIMARY KEY(performance_id,seat_id), CHECK(hold_id IS NULL OR reservation_id IS NULL)
);
CREATE TABLE reservation_item (
 reservation_id VARCHAR(36) NOT NULL REFERENCES reservation(id), seat_id BIGINT NOT NULL REFERENCES venue_seat(id),
 grade VARCHAR(3) NOT NULL, price BIGINT NOT NULL, PRIMARY KEY(reservation_id,seat_id)
);
CREATE TABLE content_entry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind VARCHAR(10) NOT NULL CHECK(kind IN ('FAQ','POST')),
 category VARCHAR(20) NOT NULL CHECK(category IN ('NOTICE','GUIDE','UPDATE')),
 titles TEXT NOT NULL, bodies TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
